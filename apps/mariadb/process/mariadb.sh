# MariaDB helpers shared by this app's scripts (after lib.sh).

DATA_DIR="$APP_DIR/data"
RUN_DIR="$APP_DIR/run"
CNF="$APP_DIR/conf/my.cnf"

# The MariaDB server: mariadbd, or a mysqld that is MariaDB's.
locate_server() {
  local bin
  if bin="$(find_bin mariadbd /usr/libexec)"; then
    echo "$bin"
    return
  fi
  if bin="$(find_bin mysqld /usr/libexec)" && "$bin" --version 2>/dev/null | grep -qi mariadb; then
    echo "$bin"
    return
  fi
  return 1
}

# Write conf/my.cnf from the settings. Extra options go in conf/conf.d/*.cnf.
write_cnf() {
  mkdir -p "$APP_DIR/conf/conf.d" "$RUN_DIR" "$DATA_DIR"
  {
    echo "# Generated by XDeck from the app's settings; changes here are overwritten."
    echo "# Add your own options in conf/conf.d/*.cnf."
    echo "[mysqld]"
    echo "datadir = $DATA_DIR"
    echo "port = ${PORT:-3306}"
    echo "bind-address = ${BIND:-127.0.0.1}"
    echo "socket = $RUN_DIR/mariadb.sock"
    echo "pid-file = $RUN_DIR/mariadb.pid"
    echo "character-set-server = utf8mb4"
    echo "collation-server = utf8mb4_general_ci"
    # mariadbd only runs as root when told so explicitly.
    if is_root; then echo "user = root"; fi
    echo
    echo "[client]"
    echo "socket = $RUN_DIR/mariadb.sock"
    echo "port = ${PORT:-3306}"
    echo
    echo "!includedir $APP_DIR/conf/conf.d"
  } | write_file "$CNF"
}

# Quote a MariaDB identifier.
sql_ident() {
  printf '`%s`' "${1//\`/\`\`}"
}

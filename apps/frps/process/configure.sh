#!/usr/bin/env bash
# Write conf/frps.toml from the app's settings.
. "$(dirname "$0")/lib.sh"
. "$(dirname "$0")/frp.sh"

umask 077
{
  echo "# Generated by XDeck from the app's settings; changes here are overwritten."
  echo "bindPort = ${BIND_PORT:-7000}"
  echo 'auth.method = "token"'
  echo "auth.token = $(toml_string "${TOKEN:?a token is required}")"
  echo "vhostHTTPPort = ${VHOST_HTTP_PORT:-8080}"
  echo "vhostHTTPSPort = ${VHOST_HTTPS_PORT:-8443}"
  if [ -n "${SUBDOMAIN_HOST:-}" ]; then echo "subDomainHost = $(toml_string "$SUBDOMAIN_HOST")"; fi
  if [ -n "${ALLOW_PORTS:-}" ]; then
    ranges=""
    for p in $(echo "$ALLOW_PORTS" | tr ',' ' '); do
      case "$p" in
        *[!0-9-]* | -* | *-) die "invalid port or range in ALLOW_PORTS: $p" ;;
        *-*) entry="{ start = ${p%-*}, end = ${p#*-} }" ;;
        *) entry="{ single = $p }" ;;
      esac
      ranges="${ranges:+$ranges, }$entry"
    done
    echo "allowPorts = [$ranges]"
  fi
  echo "webServer.addr = $(toml_string "${DASHBOARD_BIND:-127.0.0.1}")"
  echo "webServer.port = ${DASHBOARD_PORT:-7500}"
  echo "webServer.user = $(toml_string "${DASHBOARD_USER:-admin}")"
  echo "webServer.password = $(toml_string "${DASHBOARD_PASSWORD:?a dashboard password is required}")"
  echo 'log.to = "console"'
} | write_file "$CONF"
"$BIN" verify -c "$CONF" >/dev/null || die "frps rejected the configuration"
log "Wrote conf/frps.toml"
